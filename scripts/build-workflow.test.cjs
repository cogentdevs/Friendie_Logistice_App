const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const http = require('node:http');
const { attachBuild, inside } = require('./prepare-android-cache.cjs');
const { probeMetro } = require('./start-metro.cjs');
async function fixture(run) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'friendie-build-test-'));
  const workspace = path.join(root, 'workspace');
  const cacheRoot = path.join(root, 'cache');
  const source = path.join(workspace, 'android', 'build');
  await fs.mkdir(source, { recursive: true });
  await fs.mkdir(cacheRoot, { recursive: true });
  try {
    await run({
      workspace,
      cacheRoot,
      source,
      root,
      key: 'fixture',
      log: () => {},
    });
  } finally {
    const resolved = await fs.realpath(root);
    if (
      !inside(os.tmpdir(), resolved) ||
      !path.basename(resolved).startsWith('friendie-build-test-')
    )
      throw new Error('Unsafe test cleanup');
    await fs.rm(resolved, { recursive: true });
  }
}
test('generated outputs survive migration and repeated setup', async () =>
  fixture(async options => {
    await fs.writeFile(
      path.join(options.source, 'artifact.bin'),
      'generated bytes',
    );
    const result = await attachBuild({ ...options, migrate: true });
    assert.equal(result.migratedBytes, 15);
    assert.equal((await fs.lstat(options.source)).isSymbolicLink(), true);
    assert.equal(
      await fs.readFile(path.join(options.source, 'artifact.bin'), 'utf8'),
      'generated bytes',
    );
    assert.equal((await attachBuild(options)).linked, false);
  }));
test('normal setup never migrates an existing populated directory implicitly', async () =>
  fixture(async options => {
    await fs.writeFile(path.join(options.source, 'keep.txt'), 'preserve');
    await assert.rejects(attachBuild(options), /need migration/);
    assert.equal(
      await fs.readFile(path.join(options.source, 'keep.txt'), 'utf8'),
      'preserve',
    );
  }));
test('reject outside-workspace source and foreign junction without touching their files', async () =>
  fixture(async options => {
    await assert.rejects(
      attachBuild({ ...options, source: path.join(options.root, 'build') }),
      /Unsafe generated/,
    );
    const outside = path.join(options.root, 'outside');
    await fs.mkdir(outside);
    await fs.writeFile(path.join(outside, 'keep.txt'), 'safe');
    await fs.rmdir(options.source);
    await fs.symlink(outside, options.source, 'junction');
    await assert.rejects(attachBuild(options), /external build link/);
    assert.equal(
      await fs.readFile(path.join(outside, 'keep.txt'), 'utf8'),
      'safe',
    );
  }));
test('repairs a deleted generated cache target without removing the junction', async () =>
  fixture(async options => {
    await attachBuild(options);
    const destination = await fs.readlink(options.source);
    if (!inside(options.cacheRoot, destination))
      throw new Error('Unsafe fixture cache target');
    await fs.rmdir(destination);
    await attachBuild(options);
    assert.equal((await fs.stat(options.source)).isDirectory(), true);
  }));
async function serverTest(rootHeader, body, run) {
  const server = http.createServer((_req, res) => {
    if (rootHeader) res.setHeader('X-React-Native-Project-Root', rootHeader);
    res.end(body);
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  try {
    await run(server.address().port);
  } finally {
    await new Promise(resolve => server.close(resolve));
  }
}
test('reuses only healthy Metro from this workspace', async () => {
  const root = path.resolve(__dirname, '..');
  await serverTest(root, 'packager-status:running', async port =>
    assert.equal(await probeMetro(port, root), true),
  );
});
test('rejects a different project or non-Metro listener', async () => {
  const root = path.resolve(__dirname, '..');
  await serverTest(os.tmpdir(), 'packager-status:running', async port =>
    assert.rejects(probeMetro(port, root), /another server\/project/),
  );
  await serverTest(null, 'not Metro', async port =>
    assert.rejects(probeMetro(port, root), /another server\/project/),
  );
});
